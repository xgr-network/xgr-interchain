import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {buildExperienceModel,renderRepresentationInventory} from "./experience.js";
import {metaMaskTokenSpec,injectedMetaMask,requestMetaMaskToken,metaMaskFailure} from "./metamask-token.js";
const catalog=JSON.parse(readFileSync(new URL("./catalog.json",import.meta.url),"utf8"));
const model=buildExperienceModel(catalog,()=>false);
test("only receipt-backed synthetic token with valid chain metadata is importable",()=>{
 const base=metaMaskTokenSpec(model,"XGR","base");
 assert.equal(base.address,"0x2ca97eff807744f81f13c59a75a8eb0add1c715d");
 assert.equal(base.chainId,"0x2105");
 assert.equal(base.symbol,"wXGR");
 assert.equal(base.decimals,18);
 assert.equal(metaMaskTokenSpec(model,"XGR","xgrchain"),null);
 assert.equal(metaMaskTokenSpec(model,"XGR","polygon"),null);
 assert.equal(metaMaskTokenSpec(model,"ARB","arbitrum"),null,"canonical token address is not receipt-backed synthetic");
 const html=renderRepresentationInventory(model,"XGR","base");
 assert.match(html,/data-xita-add-metamask/);
 assert.match(html,/data-asset="XGR"/);
 assert.doesNotMatch(renderRepresentationInventory(model,"XGR","polygon"),/data-xita-add-metamask/);
 assert.doesNotMatch(renderRepresentationInventory(model,"XGR","xgrchain"),/data-xita-add-metamask/);
});
test("wallet watchAsset never requests accounts or signs and only switches chains on explicit click",async()=>{
 const calls=[];
 const provider={request:async args=>{calls.push(args);
   if(args.method==="eth_chainId")return calls.some(x=>x.method==="wallet_switchEthereumChain")?"0x2105":"0xa4b1";
   if(args.method==="wallet_watchAsset")return true;
   return null;
 }};
 assert.equal(await requestMetaMaskToken(provider,metaMaskTokenSpec(model,"XGR","base")),true);
 assert.deepEqual(calls.map(x=>x.method),["eth_chainId","wallet_switchEthereumChain","eth_chainId","wallet_watchAsset"]);
 assert.deepEqual(calls.at(-1).params.options,{address:"0x2ca97eff807744f81f13c59a75a8eb0add1c715d",symbol:"wXGR",decimals:18});
 const same=[];
 const ready={request:async a=>{same.push(a.method);return a.method==="eth_chainId"?"0x2105":false}};
 assert.equal(await requestMetaMaskToken(ready,metaMaskTokenSpec(model,"XGR","base")),false);
 assert.deepEqual(same,["eth_chainId","wallet_watchAsset"]);
});
test("wrong network, invalid address and rejected switches never send wallet_watchAsset",async()=>{
 const calls=[];
 const provider={request:async a=>{calls.push(a.method);return a.method==="eth_chainId"?"0x1":null}};
 await assert.rejects(()=>requestMetaMaskToken(provider,metaMaskTokenSpec(model,"XGR","base")),/different network/);
 assert.deepEqual(calls,["eth_chainId","wallet_switchEthereumChain","eth_chainId"]);
 calls.length=0;
 await assert.rejects(()=>requestMetaMaskToken(provider,{...metaMaskTokenSpec(model,"XGR","base"),address:"0x123"}),/Invalid/);
 assert.equal(calls.length,0);
 assert.match(metaMaskFailure({code:4001}),/Cancelled/);
 assert.equal(injectedMetaMask({providers:[{request:async()=>{},isMetaMask:true}]}).isMetaMask,true);
 assert.equal(injectedMetaMask({request:async()=>{}}),null);
});
